impl I18nKey {
    /// Exhaustive compile-time English & Arabic lookup table.
    #[must_use]
    pub const fn tr(self, lang: StudioLanguage) -> &'static str {
        match lang {
            StudioLanguage::English => translations::tr_en(self),
            StudioLanguage::Arabic => translations_ui::tr_ar(self),
        }
    }

    /// Returns the UAX #9 bidi-shaped UI string for the active language.
    #[must_use]
    pub fn tr_ui(self, lang: StudioLanguage) -> String {
        let raw = self.tr(lang);
        match lang {
            StudioLanguage::English => raw.to_owned(),
            StudioLanguage::Arabic => shape_mixed_ui_bidi(raw),
        }
    }
}

