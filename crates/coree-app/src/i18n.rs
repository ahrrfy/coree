/// Complete RTL/LTR desktop shell mirroring descriptor derived from [`StudioLanguage`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ShellLayoutDirections {
    pub is_rtl: bool,
    pub toolbox_on_right: bool,
    pub palette_on_left: bool,
    pub dockers_on_left: bool,
    pub egui_direction: egui::Direction,
}

impl ShellLayoutDirections {
    const CTX_DIR_KEY: &'static str = "coree_shell_egui_direction";

    /// Computes shell panel anchoring (`Toolbox`, `PaletteBar`, `Dockers`, `egui::Direction`) for `lang`.
    #[must_use]
    pub const fn from_language(lang: StudioLanguage) -> Self {
        match lang {
            StudioLanguage::English => Self {
                is_rtl: false,
                toolbox_on_right: false,
                palette_on_left: false,
                dockers_on_left: false,
                egui_direction: egui::Direction::LeftToRight,
            },
            StudioLanguage::Arabic => Self {
                is_rtl: true,
                toolbox_on_right: true,
                palette_on_left: true,
                dockers_on_left: true,
                egui_direction: egui::Direction::RightToLeft,
            },
        }
    }

    /// Persists the active horizontal [`egui::Direction`] on `ctx` and updates style cursor preview.
    pub fn apply_to_ctx(self, ctx: &egui::Context) {
        ctx.data_mut(|d| {
            d.insert_temp(egui::Id::unique(Self::CTX_DIR_KEY), self.egui_direction);
        });
        ctx.style_mut_of(ctx.theme(), |style| {
            style.visuals.text_cursor.preview = true;
        });
    }

    /// Reads the active shell [`egui::Direction`] persisted by [`Self::apply_to_ctx`].
    #[must_use]
    pub fn from_ctx(ctx: &egui::Context) -> egui::Direction {
        ctx.data(|d| d.get_temp::<egui::Direction>(egui::Id::unique(Self::CTX_DIR_KEY)))
            .unwrap_or(egui::Direction::LeftToRight)
    }

    #[must_use]
    pub fn horizontal_layout(self, cross_align: egui::Align) -> egui::Layout {
        egui::Layout::from_main_dir_and_cross_align(self.egui_direction, cross_align)
    }

    #[must_use]
    pub fn horizontal_wrapped_layout(self, cross_align: egui::Align) -> egui::Layout {
        egui::Layout::from_main_dir_and_cross_align(self.egui_direction, cross_align)
            .with_main_wrap(true)
    }

    #[must_use]
    pub fn opposite_horizontal_layout(self, cross_align: egui::Align) -> egui::Layout {
        let opp = match self.egui_direction {
            egui::Direction::RightToLeft => egui::Direction::LeftToRight,
            _ => egui::Direction::RightToLeft,
        };
        egui::Layout::from_main_dir_and_cross_align(opp, cross_align)
    }

    #[must_use]
    pub fn vertical_layout(self) -> egui::Layout {
        let halign = match self.egui_direction {
            egui::Direction::RightToLeft => egui::Align::Max,
            _ => egui::Align::Min,
        };
        egui::Layout::top_down(halign)
    }

    pub fn with_horizontal<R>(
        self,
        ui: &mut egui::Ui,
        add_contents: impl FnOnce(&mut egui::Ui) -> R,
    ) -> egui::InnerResponse<R> {
        let initial_size = egui::vec2(
            ui.available_size_before_wrap().x,
            ui.spacing().interact_size.y,
        );
        ui.allocate_ui_with_layout(
            initial_size,
            self.horizontal_layout(egui::Align::Center),
            add_contents,
        )
    }

    pub fn with_horizontal_wrapped<R>(
        self,
        ui: &mut egui::Ui,
        add_contents: impl FnOnce(&mut egui::Ui) -> R,
    ) -> egui::InnerResponse<R> {
        let initial_size = egui::vec2(
            ui.available_size_before_wrap().x,
            ui.spacing().interact_size.y,
        );
        ui.allocate_ui_with_layout(
            initial_size,
            self.horizontal_wrapped_layout(egui::Align::Center),
            add_contents,
        )
    }

    pub fn with_horizontal_wrapped_align<R>(
        self,
        ui: &mut egui::Ui,
        cross_align: egui::Align,
        add_contents: impl FnOnce(&mut egui::Ui) -> R,
    ) -> egui::InnerResponse<R> {
        let initial_size = egui::vec2(
            ui.available_size_before_wrap().x,
            ui.spacing().interact_size.y,
        );
        ui.allocate_ui_with_layout(
            initial_size,
            self.horizontal_wrapped_layout(cross_align),
            add_contents,
        )
    }

    pub fn with_opposite_horizontal<R>(
        self,
        ui: &mut egui::Ui,
        add_contents: impl FnOnce(&mut egui::Ui) -> R,
    ) -> egui::InnerResponse<R> {
        let initial_size = egui::vec2(
            ui.available_size_before_wrap().x,
            ui.spacing().interact_size.y,
        );
        ui.allocate_ui_with_layout(
            initial_size,
            self.opposite_horizontal_layout(egui::Align::Center),
            add_contents,
        )
    }

    pub fn with_vertical<R>(
        self,
        ui: &mut egui::Ui,
        add_contents: impl FnOnce(&mut egui::Ui) -> R,
    ) -> egui::InnerResponse<R> {
        ui.with_layout(self.vertical_layout(), add_contents)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn i18n_keys_and_rtl_shell_mirroring_are_exhaustive() {
        let en = ShellLayoutDirections::from_language(StudioLanguage::English);
        let ar = ShellLayoutDirections::from_language(StudioLanguage::Arabic);
        assert!(!en.is_rtl && !en.toolbox_on_right && !en.palette_on_left && !en.dockers_on_left);
        assert!(ar.is_rtl && ar.toolbox_on_right && ar.palette_on_left && ar.dockers_on_left);
        assert_eq!(en.egui_direction, egui::Direction::LeftToRight);
        assert_eq!(ar.egui_direction, egui::Direction::RightToLeft);

        assert_eq!(I18nKey::MenuFile.tr(StudioLanguage::English), "File");
        assert_eq!(I18nKey::MenuFile.tr(StudioLanguage::Arabic), "ملف");
        assert_eq!(I18nKey::DlgFillRgbLabel.tr(StudioLanguage::English), "RGB:");
        assert!(!I18nKey::DlgFillRgbLabel
            .tr(StudioLanguage::Arabic)
            .is_empty());
        assert_eq!(
            I18nKey::CtxUnlinkClone.tr(StudioLanguage::English),
            "Unlink Clone"
        );
        assert!(!I18nKey::CtxUnlinkClone
            .tr(StudioLanguage::Arabic)
            .is_empty());
        assert!(!I18nKey::StatusSnapActive
            .tr_ui(StudioLanguage::Arabic)
            .is_empty());
        assert!(!I18nKey::ErrorLayerLocked
            .tr_ui(StudioLanguage::Arabic)
            .is_empty());
        assert!(!I18nKey::ErrorInvalidInput
            .tr_ui(StudioLanguage::Arabic)
            .is_empty());
        for mixed_key in [
            I18nKey::MenuSendLightBurn,
            I18nKey::SaveAsTemplateCdt,
            I18nKey::MenuProofColors,
            I18nKey::MenuAboutCoree,
        ] {
            let raw = mixed_key.tr(StudioLanguage::Arabic);
            let ui_shaped = mixed_key.tr_ui(StudioLanguage::Arabic);
            assert_eq!(ui_shaped, shape_mixed_ui_bidi(raw));
            assert_ne!(
                ui_shaped, raw,
                "mixed Arabic+Latin menu key {mixed_key:?} must undergo UAX #9 BiDi run ordering via tr_ui"
            );
        }

        let ctx = egui::Context::default();
        ar.apply_to_ctx(&ctx);
        assert_eq!(
            ShellLayoutDirections::from_ctx(&ctx),
            egui::Direction::RightToLeft
        );
        assert_eq!(
            ar.horizontal_layout(egui::Align::Center).main_dir(),
            egui::Direction::RightToLeft
        );
        assert_eq!(
            ar.opposite_horizontal_layout(egui::Align::Center)
                .main_dir(),
            egui::Direction::LeftToRight
        );
        en.apply_to_ctx(&ctx);
        assert_eq!(
            ShellLayoutDirections::from_ctx(&ctx),
            egui::Direction::LeftToRight
        );
    }
}
